package cli

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/urbforge/urbex-cli/internal/envrepo"
)

func TestRefuseGenerated(t *testing.T) {
	repo := envrepo.Repo{Path: t.TempDir()}
	dir := filepath.Join(repo.Path, "environments", "staging", "my-app", "db")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	os.WriteFile(filepath.Join(dir, envrepo.GeneratedFile), []byte("# generated\nPOSTGRES_USER=urbex\n"), 0o644)
	os.WriteFile(filepath.Join(dir, envrepo.GeneratedSecretsFile), []byte("POSTGRES_PASSWORD=ENC[x]\nsops_version=3\n"), 0o644)

	for _, key := range []string{"POSTGRES_USER", "POSTGRES_PASSWORD"} {
		err := refuseGenerated(repo, "staging", "my-app", "db", key)
		if err == nil || !strings.Contains(err.Error(), key+" is generated by urbex for db") {
			t.Errorf("%s: expected a refusal, got %v", key, err)
		}
	}
	if err := refuseGenerated(repo, "staging", "my-app", "db", "TZ"); err != nil {
		t.Errorf("a key urbex does not generate is the user's: %v", err)
	}
	if err := refuseGenerated(repo, "staging", "my-app", "api", "POSTGRES_USER"); err != nil {
		t.Errorf("another service has no generated file: %v", err)
	}
}
