package bootstrap

import (
	"fmt"
	"strconv"
	"strings"

	"github.com/urbforge/urbex-cli/internal/credentials"
	"github.com/urbforge/urbex-cli/internal/platform"
)

// AlertsProvisioningFile is the Grafana provisioning file, in the
// observability Stack, that sends Urbex's alerts to the channels of
// observability.alerts (urbforge/urbex-cli#95). urbex writes it when a
// channel is configured, and removes it when none is.
const AlertsProvisioningFile = "grafana/provisioning/alerting/urbex-notifications.yml"

// The secrets the provisioning file reads from Grafana's environment
// (Grafana expands $VAR in provisioning files): the Stack's secrets.
const (
	alertsTelegramTokenVar = "URBEX_ALERTS_TELEGRAM_BOT_TOKEN"
	alertsDiscordURLVar    = "URBEX_ALERTS_DISCORD_WEBHOOK_URL"
	alertsWebhookURLVar    = "URBEX_ALERTS_WEBHOOK_URL"
)

// The grouping and repeat of the alerts' notifications: one message per
// alert and machine, gathered for 30 s, again at most every 4 hours while
// it fires - a flapping disk doesn't fill the chat.
const (
	alertsGroupWait      = "30s"
	alertsGroupInterval  = "5m"
	alertsRepeatInterval = "4h"
)

// alertsMessage is the notifications' text: per alert, firing or
// resolved, its summary and severity, the project, service, env and host
// it is about, and a link to it in Grafana. A rule Grafana couldn't
// evaluate (its data source down) has no values for its summary: the
// message names the rule instead.
const alertsMessage = `{{ define "urbex.message" }}{{ range .Alerts }}{{ if eq .Status "firing" }}FIRING{{ else }}RESOLVED{{ end }} [{{ or .Labels.severity "info" }}] {{ if or (eq .Labels.alertname "DatasourceError") (eq .Labels.alertname "DatasourceNoData") }}could not evaluate "{{ .Labels.rulename }}" ({{ .Labels.alertname }}){{ else }}{{ or .Annotations.summary .Labels.alertname }}{{ end }}{{ with .Labels.project }} - project {{ . }}{{ end }}{{ with .Labels.service }} - service {{ . }}{{ end }}{{ with .Labels.env }} - {{ . }}{{ end }}{{ with .Labels.host }} - {{ . }}{{ end }}
{{ .GeneratorURL }}
{{ end }}{{ end }}`

// AlertsProvisioning returns the provisioning file for cfg's alert
// channels and the secrets it reads, or "" when none is configured.
// Missing credentials for a configured channel are an error, naming them.
func AlertsProvisioning(cfg platform.AlertsConfig, creds *credentials.Credentials) (string, map[string]string, error) {
	if !cfg.Any() {
		return "", nil, nil
	}
	var missing []string
	secrets := map[string]string{}
	var receivers strings.Builder
	message := strconv.Quote(`{{ template "urbex.message" . }}`)
	if t := cfg.Telegram; t != nil {
		if creds.TelegramBotToken == "" {
			missing = append(missing, "telegramBotToken")
		}
		secrets[alertsTelegramTokenVar] = creds.TelegramBotToken
		fmt.Fprintf(&receivers, `      - uid: urbex-telegram
        type: telegram
        settings:
          bottoken: $%s
          chatid: %s
          message: %s
          disable_web_page_preview: true
`, alertsTelegramTokenVar, strconv.Quote(t.ChatID), message)
	}
	if cfg.Discord {
		if creds.DiscordWebhookURL == "" {
			missing = append(missing, "discordWebhookUrl")
		}
		secrets[alertsDiscordURLVar] = creds.DiscordWebhookURL
		fmt.Fprintf(&receivers, `      - uid: urbex-discord
        type: discord
        settings:
          url: $%s
          message: %s
`, alertsDiscordURLVar, message)
	}
	if cfg.Webhook {
		if creds.AlertsWebhookURL == "" {
			missing = append(missing, "alertsWebhookUrl")
		}
		secrets[alertsWebhookURLVar] = creds.AlertsWebhookURL
		fmt.Fprintf(&receivers, `      - uid: urbex-webhook
        type: webhook
        settings:
          url: $%s
`, alertsWebhookURLVar)
	}
	if len(missing) > 0 {
		return "", nil, fmt.Errorf("observability.alerts needs the credential(s) %s: store them with 'urbex-op set <key>' (see docs/reference/credentials.md in urbforge/urbex)", strings.Join(missing, ", "))
	}
	var b strings.Builder
	b.WriteString(`# Generated by urbex bootstrap from observability.alerts in
# urbex.platform.yaml (urbforge/urbex-cli#95) - do not edit. Sends the
# alerts of this Grafana to the channels configured there; their secrets
# come from the Stack's encrypted secrets, through Grafana's environment.
apiVersion: 1
templates:
  - orgId: 1
    name: urbex
    template: |
`)
	for _, line := range strings.Split(alertsMessage, "\n") {
		b.WriteString("      " + line + "\n")
	}
	b.WriteString(`contactPoints:
  - orgId: 1
    name: urbex
    receivers:
`)
	b.WriteString(receivers.String())
	// The whole policy tree: this Grafana is the platform's, and its
	// alerts are Urbex's (Grafana 13 has no default contact point to
	// route the others to).
	fmt.Fprintf(&b, `policies:
  - orgId: 1
    receiver: urbex
    group_by: [alertname, service, host]
    group_wait: %s
    group_interval: %s
    repeat_interval: %s
`, alertsGroupWait, alertsGroupInterval, alertsRepeatInterval)
	return b.String(), secrets, nil
}
