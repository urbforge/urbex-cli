// SecretWriter writes a secrets file encrypted for the platform's age key
// (secrets.Store; a fake in tests, which have no sops).
type SecretWriter interface {
	Write(ctx context.Context, path string, values map[string]string) error
}

// PlatformStack is a platform service Komodo deploys from the GitOps repo
// like a project service (ADR-0027): its folder platform/<Dir>/, with the
// files of urbex-cli's platform/stacks/<Dir>, a config.env and a
// secrets.sops.env; the Stack Name runs on the Server of the same name.
type PlatformStack struct {
	Name, Dir string
	Config    map[string]string
	Secrets   map[string]string
}

// ComposeWrapper is the command every Stack deployed from the GitOps repo
// runs `docker compose up` through: a script on the LXC (Ansible role
// sops-tools) that decrypts the Stack's secrets, if it has any, for the
// duration of the command.
const ComposeWrapper = "/opt/urbex/bin/urbex-compose [[COMPOSE_COMMAND]]"

// PlatformStacksDir is the GitOps repo's folder of the platform's Stacks.
const PlatformStacksDir = "platform"

// platformStacks are the platform services deployed from the GitOps
// repo: Keycloak, the observability stack and, with Cloudflare, the
// tunnel, whose connector token is tunnelToken.
func (o *Orchestrator) platformStacks(tunnelToken string) []PlatformStack {
	keycloak := map[string]string{
		// The development database's credentials, as Keycloak 26.0
		// created it: later versions default to others and can't open it
		// otherwise. The file stays inside the container's volume.
		"KC_DB_USERNAME":              "sa",
		"KC_DB_PASSWORD":              "password",
		"KC_BOOTSTRAP_ADMIN_USERNAME": "admin",
		// Logs worth having in Loki: every request, and logins at INFO.
		"KC_HTTP_ACCESS_LOG_ENABLED":                         "true",
		"KC_SPI_EVENTS_LISTENER_JBOSS_LOGGING_SUCCESS_LEVEL": "info",
	}
	if pub := PublicEndpointsFor(o.Config); pub.Keycloak != "" {
		// Public through the platform's tunnel (ADR-0022): the issuer users
		// and apps see; services inside may use the internal name for
		// back-channel calls.
		keycloak["KC_HOSTNAME"] = "https://" + pub.Keycloak
		keycloak["KC_HOSTNAME_BACKCHANNEL_DYNAMIC"] = "true"
		keycloak["KC_PROXY_HEADERS"] = "xforwarded"
		keycloak["KC_HTTP_ENABLED"] = "true"
	}
	stacks := []PlatformStack{
		{Name: Hostname("keycloak"), Dir: "keycloak", Config: keycloak,
			Secrets: map[string]string{"KC_BOOTSTRAP_ADMIN_PASSWORD": o.Credentials.KeycloakAdminPassword}},
		{Name: Hostname("observability"), Dir: "observability", Config: map[string]string{},
			Secrets: map[string]string{"GF_SECURITY_ADMIN_PASSWORD": o.Credentials.GrafanaAdminPassword}},
	}
	if o.Config.Cloudflare.Enabled() {
		stacks = append(stacks, PlatformStack{Name: Hostname(TunnelService.Name), Dir: "tunnel", Config: map[string]string{},
			Secrets: map[string]string{"TUNNEL_TOKEN": tunnelToken}})
	}
	return stacks
}

// secretWriter is o.Secrets, or a sops-backed store for the platform's
// age key.
func (o *Orchestrator) secretWriter() (SecretWriter, error) {
	if o.Secrets != nil {
		return o.Secrets, nil
	}
	return secrets.NewStore(o.Credentials.AgeKey)
}

// writePlatformStacks writes each Stack's folder into the GitOps repo:
// the embedded files, config.env, and the secrets encrypted with SOPS.
func (o *Orchestrator) writePlatformStacks(ctx context.Context, gitopsRepoPath string, stacks []PlatformStack) error {
	store, err := o.secretWriter()
	if err != nil {
		return err
	}
	for _, st := range stacks {
		dir := filepath.Join(gitopsRepoPath, PlatformStacksDir, st.Dir)
		src := path.Join("stacks", st.Dir)
		err := fs.WalkDir(assets.Stacks, src, func(p string, d fs.DirEntry, err error) error {
			if err != nil || d.IsDir() {
				return err
			}
			data, err := assets.Stacks.ReadFile(p)
			if err != nil {
				return err
			}
			dest := filepath.Join(dir, filepath.FromSlash(strings.TrimPrefix(p, src+"/")))
			if err := os.MkdirAll(filepath.Dir(dest), 0o755); err != nil {
				return err
			}
			return os.WriteFile(dest, data, 0o644)
		})
		if err != nil {
			return fmt.Errorf("writing the %s stack: %w", st.Dir, err)
		}
		if err := os.WriteFile(filepath.Join(dir, "config.env"), []byte(renderEnv(st.Config)), 0o644); err != nil {
			return err
		}
		if err := store.Write(ctx, filepath.Join(dir, "secrets.sops.env"), st.Secrets); err != nil {
			return fmt.Errorf("encrypting the %s stack's secrets: %w", st.Dir, err)
		}
	}
	return nil
}

func renderEnv(vars map[string]string) string {
	var b strings.Builder
	b.WriteString("# Generated by urbex bootstrap - non-secret configuration of this\n")
	b.WriteString("# platform Stack; secrets are in secrets.sops.env.\n")
	keys := make([]string, 0, len(vars))
	for k := range vars {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		b.WriteString(k + "=" + vars[k] + "\n")
	}
	return b.String()
}

// stackDeploy is a Stack Komodo deploys, with its config and kind tag.
type stackDeploy struct {
	name string
	cfg  komodo.StackConfig
	tag  string
}

// platformStackDeploys are the platform's Stacks, deployed from the GitOps
// repo on the Server of the same name, tagged platform. Their compose
// project is "urbex", as when Ansible ran them: an existing platform
// keeps its volumes, and so its data.
func (o *Orchestrator) platformStackDeploys(stacks []PlatformStack) ([]stackDeploy, error) {
	internal, err := InternalEndpointsFor(o.Config)
	if err != nil {
		return nil, err
	}
	var deploys []stackDeploy
	for _, st := range stacks {
		deploys = append(deploys, stackDeploy{name: st.Name, tag: PlatformTag, cfg: komodo.StackConfig{
			ServerID:     st.Name,
			GitProvider:  internal.Registry,
			GitAccount:   GiteaAdminUser,
			Repo:         o.Config.Git.Org + "/" + GitOpsRepoName,
			Branch:       TrunkBranch,
			RunDirectory: PlatformStacksDir + "/" + st.Dir,
			ProjectName:  "urbex",
			ConfigFiles: []komodo.ConfigFile{
				{Path: "config.env", Requires: "Redeploy"},
				{Path: "secrets.sops.env", Requires: "Redeploy"},
			},
			ComposeCmdWrapper: ComposeWrapper,
		}})
	}
	return deploys, nil
}

// deployStacks has Komodo create, tag and deploy the Stacks. They don't
// depend on each other - each on its own Server, or an agent next to a
// service - so they are deployed all at once (urbforge/urbex-cli#30):
// the time of the slowest, not of all of them. Every deploy runs to its
// end; the error names each Stack that failed.
func (o *Orchestrator) deployStacks(ctx context.Context, k KomodoAPI, deploys []stackDeploy) error {
	for _, d := range deploys {
		if err := k.EnsureStack(ctx, d.name, d.cfg); err != nil {
			return fmt.Errorf("komodo stack %s: %w", d.name, err)
		}
		if err := k.TagResource(ctx, "Stack", d.name, d.tag); err != nil {
			return err
		}
	}
	errs := make([]error, len(deploys))
	var wg sync.WaitGroup
	for i, d := range deploys {
		wg.Add(1)
		go func() {
			defer wg.Done()
			done, err := k.DeployStack(ctx, d.name)
			switch {
			case err != nil:
				errs[i] = fmt.Errorf("komodo stack %s: %w", d.name, err)
			case !done.Success:
				errs[i] = fmt.Errorf("komodo could not deploy stack %s - see its last update in Komodo", d.name)
			}
		}()
	}
	wg.Wait()
	if err := errors.Join(errs...); err != nil {
		return err
	}
	for _, d := range deploys {
		fmt.Fprintf(o.Out, "Deployed %s with Komodo.\n", d.name)
	}
	return nil
}
