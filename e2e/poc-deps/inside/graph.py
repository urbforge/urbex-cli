"""The second scenario of the PoC, the dependency graph Teg proposed.

Six blocks, three levels and a diamond. Every block's main service (`app`)
listens at once and becomes healthy a few seconds later (a file appears), so
"the container runs", "the port answers" and "it can take calls" are three
different moments. A consumer that starts too early finds `/ready` missing
and exits, as an application does when its dependency is not there.

  G1  a wait service in each block, probing `/ready` (the application's own readiness)
  G2  the same, probing only the TCP port. A control: it must NOT keep the
      order, which shows why the probe has to be the application's own
  G3  a driver outside the Stacks: topological order, health read from Komodo
  G4  as G1, with acme-db failing
  G5  as G3, with acme-db failing

The time a block may wait is a budget per level of the graph, not a fixed
number. With every Stack deployed at once, a block's wait starts at the
beginning, so it has to cover the whole chain upstream of it: the budget
times the longest path to it. The driver starts a block's clock when it
deploys it, so one budget is enough.

It is run by poc.py (`poc.py run G1 ...`) and shares its Komodo client and
container monitor.
"""
import json
import os
import re
import threading
import time

import poc

GRAPH = {
    "dns": {"deps": [], "start": 8},
    "gitea": {"deps": ["dns"], "start": 10},
    "keycloak": {"deps": ["gitea"], "start": 12, "db": True},
    "photos": {"deps": ["keycloak"], "start": 5, "healthcheck": False},
    "acme-db": {"deps": ["gitea"], "start": 10},
    "acme-api": {"deps": ["acme-db", "keycloak"], "start": 5},
}
BUDGET = 45  # seconds a block may wait per level of the graph
TESTS = {
    "G1": {"mode": "waithttp", "driver": False, "fail": []},
    "G2": {"mode": "waittcp", "driver": False, "fail": [], "control": True},
    "G3": {"mode": "plain", "driver": True, "fail": []},
    "G4": {"mode": "waithttp", "driver": False, "fail": ["acme-db"]},
    "G5": {"mode": "plain", "driver": True, "fail": ["acme-db"]},
}
DESCRIPTIONS = {
    "G1": "wait service in each block, probing the application's /ready",
    "G2": "control, wait service probing only the TCP port (must not keep the order)",
    "G3": "driver outside Komodo, topological order, health read from Komodo",
    "G4": "as G1 with acme-db failing, timeout per level of the graph",
    "G5": "as G3 with acme-db failing",
}


def stack(block):
    return f"poc-g-{block}"


def container(block):
    return f"g-{block}/app"


def depth(block):
    """Blocks in the longest chain upstream of `block` (0 for a block with no dependencies)."""
    deps = GRAPH[block]["deps"]
    return max((1 + depth(d) for d in deps), default=0)


def blocked_by(fail):
    """The blocks that cannot become ready when `fail` blocks fail."""
    out = set(fail)
    changed = True
    while changed:
        changed = False
        for b, s in GRAPH.items():
            if b not in out and any(d in out for d in s["deps"]):
                out.add(b)
                changed = True
    return out


# ------------------------------------------------------------ The compose files


def compose(block, mode, fail):
    spec = GRAPH[block]
    timeout = depth(block) * BUDGET
    deps = spec["deps"]
    wait = mode != "plain" and deps
    probe = (
        "wget -q -O /dev/null -T 2 http://$$d:8080/ready"
        if mode == "waithttp"
        else "nc -w 2 $$d 8080 </dev/null >/dev/null 2>&1"
    )
    out = [f'# Block "{block}", generated by graph.py ({mode}).', "services:"]
    if wait:
        out += [
            "  wait:",
            "    image: docker.io/library/busybox:1.37",
            '    restart: "no"',
            "    command:",
            "      - sh",
            "      - -c",
            "      - |",
            '        echo "$$(date +%s) wait start"',
            f"        end=$$(( $$(date +%s) + {timeout} ))",
            f"        for d in {' '.join(deps)}; do",
            f"          until {probe}; do",
            '            [ $$(date +%s) -ge $$end ] && { echo "$$(date +%s) wait: gave up waiting for $$d"; exit 1; }',
            "            sleep 1",
            "          done",
            '          echo "$$(date +%s) wait: $$d ok"',
            "        done",
            "    networks: [pocnet]",
            "",
        ]
    script = [f'echo "$$(date +%s) {block} start"']
    if block in fail:
        script += [f'echo "$$(date +%s) {block}: failing on purpose"', "exit 1"]
    if deps:
        script += [
            f"for d in {' '.join(deps)}; do",
            f'  wget -q -O /dev/null -T 2 http://$$d:8080/ready || {{ echo "$$(date +%s) {block}: dependency $$d not ready"; exit 1; }}',
            "done",
        ]
    script += [
        "mkdir -p /www",
        f'(sleep {spec["start"]}; touch /www/ready; echo "$$(date +%s) {block} ready") &',
        "exec httpd -f -p 8080 -h /www",
    ]
    out += [
        "  app:",
        "    image: docker.io/library/busybox:1.37",
        "    restart: unless-stopped",
    ]
    needs = []
    if wait:
        needs.append("      wait:\n        condition: service_completed_successfully")
    if spec.get("db"):
        needs.append("      db:\n        condition: service_healthy")
    if needs:
        out += ["    depends_on:"] + needs
    out += ["    command:", "      - sh", "      - -c", "      - |"] + [f"        {line}" for line in script]
    if spec.get("healthcheck", True):
        out += [
            "    healthcheck:",
            '      test: ["CMD", "test", "-f", "/www/ready"]',
            "      interval: 2s",
            "      timeout: 3s",
            "      retries: 60",
        ]
    out += ["    networks:", "      pocnet:", f"        aliases: [{block}]"]
    if spec.get("db"):
        out += [
            "",
            "  db:",
            "    image: docker.io/library/busybox:1.37",
            "    restart: unless-stopped",
            "    command: [sh, -c, 'sleep 6; touch /tmp/ready; exec sleep 86400']",
            "    healthcheck:",
            '      test: ["CMD", "test", "-f", "/tmp/ready"]',
            "      interval: 2s",
            "      timeout: 3s",
            "      retries: 60",
            "    networks: [pocnet]",
        ]
    out += ["", "networks:", "  pocnet:", "    external: true", ""]
    return "\n".join(out)


def write_blocks(test):
    for b in GRAPH:
        d = f"/etc/komodo/poc/graph-{test['name']}/{b}"
        os.makedirs(d, exist_ok=True)
        open(f"{d}/compose.yaml", "w").write(compose(b, test["mode"], test["fail"]))


def stack_config(test, block):
    extra = {}
    if test["mode"] != "plain" and GRAPH[block]["deps"]:
        extra["ignore_services"] = ["wait"]
    return {
        "server_id": "local",
        "files_on_host": True,
        "run_directory": f"/etc/komodo/poc/graph-{test['name']}/{block}",
        "file_paths": ["compose.yaml"],
        **extra,
    }


# ------------------------------------------------------------------- Readiness


def find(obj, key):
    """First value of `key` anywhere in a JSON document."""
    if isinstance(obj, dict):
        if key in obj:
            return obj[key]
        for v in obj.values():
            r = find(v, key)
            if r is not None:
                return r
    elif isinstance(obj, list):
        for v in obj:
            r = find(v, key)
            if r is not None:
                return r
    return None


def services(block):
    return ["app"] + (["db"] if GRAPH[block].get("db") else [])


def komodo_ready(k, block, shown):
    """What Komodo says about the block's containers, read from Docker at that moment.

    Healthy when the container reports it, or running when it has no healthcheck.
    (ListStackServices follows the Stack's refresh and arrives about 12 s late
    for each level, so the driver asks the container itself.)"""
    for service in services(block):
        c = k.call("read", "InspectStackContainer", {"stack": stack(block), "service": service})
        shown.setdefault(f"{block}/{service}", c)
        state = find(c, "State")
        if not isinstance(state, dict):  # an answer of another shape: read it as text
            text = json.dumps(c)
            if '"unhealthy"' in text or '"starting"' in text:
                return False
            if '"healthy"' in text or (GRAPH[block].get("healthcheck", True) is False and '"running"' in text):
                continue
            return False
        health = (find(state, "Health") or {}).get("Status")
        status = state.get("Status")
        if health is not None:
            if health != "healthy":
                return False
        elif status != "running":
            return False
    return True


# ---------------------------------------------------------------------- Deploy


def deploy_parallel(k, test):
    results, threads = [], []

    def one(block):
        try:
            results.append(k.execute("DeployStack", {"stack": stack(block)}))
        except Exception as e:
            results.append({"type": "DeployStack", "params": {"stack": stack(block)}, "ok": False, "seconds": 0, "failure": str(e)})

    for b in GRAPH:
        t = threading.Thread(target=one, args=(b,))
        t.start()
        threads.append(t)
    for t in threads:
        t.join()
    return results, {}, {}


def deploy_driver(k, test):
    """Topological order: a block deploys once every block it needs is healthy."""
    state = {b: "pending" for b in GRAPH}
    results, shown, decided = [], {}, {}
    lock = threading.Lock()

    def one(block):
        t0 = time.time()
        try:
            r = k.execute("DeployStack", {"stack": stack(block)})
        except Exception as e:
            r = {"type": "DeployStack", "params": {"stack": stack(block)}, "ok": False, "seconds": 0, "failure": str(e)}
        with lock:
            results.append(r)
        ok = r["ok"]
        deadline = time.time() + BUDGET
        while ok and time.time() < deadline:
            try:
                if komodo_ready(k, block, shown):
                    break
            except Exception as e:
                shown.setdefault(f"error-{block}", str(e))
            time.sleep(1)
        else:
            ok = False
        with lock:
            state[block] = "healthy" if ok else "failed"
            decided[block] = round(time.time() - t0, 1)

    threads = []
    while True:
        with lock:
            for b, s in GRAPH.items():
                if state[b] != "pending":
                    continue
                if any(state[d] in ("failed", "blocked") for d in s["deps"]):
                    state[b] = "blocked"
                elif all(state[d] == "healthy" for d in s["deps"]):
                    state[b] = "deploying"
                    t = threading.Thread(target=one, args=(b,))
                    t.start()
                    threads.append(t)
            open_ = [b for b, s in state.items() if s in ("pending", "deploying")]
        if not open_:
            break
        time.sleep(0.5)
    for t in threads:
        t.join()
    return results, {"driver_state": state, "driver_decided_after_s": decided}, {"inspect_stack_container": shown}


# ------------------------------------------------------------------------ Test


def run_test(name, k):
    test = {"name": name, **TESTS[name]}
    poc.clean(k)
    time.sleep(2)
    write_blocks(test)
    for b in GRAPH:
        k.ensure("Stack", stack(b), stack_config(test, b))
    print(f"\n== {name}: {DESCRIPTIONS[name]}", flush=True)

    blocked = blocked_by(test["fail"])
    expected = [b for b in GRAPH if b not in blocked]
    mon = poc.Monitor()
    mon.start()
    t0 = time.time()
    try:
        actions, extra, komodo_view = (deploy_driver if test["driver"] else deploy_parallel)(k, test)
    except Exception as e:
        actions, extra, komodo_view = [{"type": "error", "ok": False, "seconds": round(time.time() - t0, 1), "failure": str(e)}], {}, {}
    returned = round(time.time() - t0, 1)

    def ready(snapshot, b):
        v = snapshot.get(container(b))
        if not v:
            return False
        return v["health"] == "healthy" if GRAPH[b].get("healthcheck", True) else v["status"] == "running"

    deadline = time.time() + 180
    converged_at = None
    while time.time() < deadline:
        snap = poc.snapshot()
        if all(ready(snap, b) for b in expected):
            converged_at = round(time.time() - t0, 1)
            break
        time.sleep(2)
    time.sleep(3)
    mon.halt.set()
    mon.join()
    final = poc.snapshot()

    def ready_at(b):
        if GRAPH[b].get("healthcheck", True):
            return mon.first(container(b), health="healthy")
        return mon.first(container(b), status="running")

    rows = {}
    for b, s in GRAPH.items():
        first = mon.first(container(b), status="running")
        needs = [ready_at(d) for d in s["deps"]]
        ordered = None
        if first is not None and all(t is not None for t in needs):
            ordered = all(first >= t - 1 for t in needs)
        elif first is not None:
            ordered = False
        rows[b] = {
            "started_at": first,
            "ready_at": ready_at(b),
            "started_after_deps_ready": ordered,
            "restarts": final.get(container(b), {}).get("restarts"),
            "expected_ready": b in expected,
            "never_started": first is None,
        }
    ordered = all(x["started_after_deps_ready"] is not False for x in rows.values() if not x["never_started"])
    # The failed block itself runs and fails on purpose; the ones that depend on it must never start.
    held = all(rows[b]["never_started"] for b in blocked if b not in test["fail"])
    ran = all(rows[b]["ready_at"] is not None for b in expected)
    quiet = sum(rows[b]["restarts"] or 0 for b in expected) == 0
    if test.get("control"):
        verdict = (not ordered) or not quiet  # the control must show the TCP probe is not enough
    else:
        verdict = ordered and held and ran and quiet
    result = {
        "verdict": bool(verdict),
        "test": name,
        "description": DESCRIPTIONS[name],
        "komodo": poc.VERSION,
        "actions": actions,
        "deploy_returned_after_s": returned,
        "converged_after_s": converged_at,
        "expected_ready": expected,
        "blocks": rows,
        "not_ready_lines": poc.logs_count("not ready"),
        "stack_states": {i["name"]: i["info"]["state"] for i in k.call("read", "ListStacks") if i["name"].startswith("poc-g-")},
        **extra,
        "komodo_view": komodo_view,
        "final": final,
        "events": mon.events,
    }
    os.makedirs(poc.RESULTS, exist_ok=True)
    json.dump(result, open(f"{poc.RESULTS}/{name}.g.json", "w"), indent=1)
    write_md(result)
    print(json.dumps({k_: v for k_, v in result.items() if k_ not in ("events", "final", "komodo_view")}, indent=1), flush=True)
    return result


def write_md(r):
    lines = [f"# {r['test']}: {r['description']}", "", f"Komodo {r['komodo']}", ""]
    lines += [
        f"- verdict: {'PASS' if r['verdict'] else 'FAIL'}" + (" (a control passes when the TCP probe breaks the order)" if TESTS[r["test"]].get("control") else ""),
        f"- deploys returned after {r['deploy_returned_after_s']} s; every expected block ready after {r['converged_after_s']} s (None = never)",
        f"- lines saying a dependency was not ready: {r['not_ready_lines']}",
        f"- Komodo's Stack states: {r['stack_states']}",
    ]
    if "driver_state" in r:
        lines.append(f"- the driver's verdict: {r['driver_state']}, decided after {r['driver_decided_after_s']}")
    lines += ["", "## Blocks", "", "| block | started | ready | after deps ready | restarts | expected ready | never started |", "|---|---|---|---|---|---|---|"]
    for b, x in r["blocks"].items():
        lines.append(f"| {b} | {x['started_at']} | {x['ready_at']} | {x['started_after_deps_ready']} | {x['restarts']} | {x['expected_ready']} | {x['never_started']} |")
    lines += ["", "## What Komodo ran", ""]
    for a in r["actions"]:
        lines.append(f"- {a['type']} {json.dumps(a.get('params'))}: ok={a['ok']} in {a['seconds']} s")
        if a.get("failure"):
            lines += ["", "```", a["failure"], "```", ""]
    if r.get("komodo_view", {}).get("inspect_stack_container"):
        lines += ["", "## InspectStackContainer, the first answer for each service", ""]
        for b, v in r["komodo_view"]["inspect_stack_container"].items():
            lines += [f"`{b}`", "", "```", json.dumps(v)[:1200], "```", ""]
    lines += ["", "## Timeline (seconds from the start)", "", "| t | container | status | health | restarts | exit |", "|---|---|---|---|---|---|"]
    for e in r["events"][:250]:
        lines.append(f"| {e.get('t')} | {e.get('name')} | {e.get('status', e.get('error', ''))} | {e.get('health', '')} | {e.get('restarts', '')} | {e.get('exit', '')} |")
    open(f"{poc.RESULTS}/{r['test']}.md", "w").write("\n".join(lines) + "\n")


def write_summary():
    rows = []
    for f in sorted(os.listdir(poc.RESULTS)) if os.path.isdir(poc.RESULTS) else []:
        if not f.endswith(".g.json"):
            continue
        r = json.load(open(f"{poc.RESULTS}/{f}"))
        ordered = all(x["started_after_deps_ready"] is not False for x in r["blocks"].values() if not x["never_started"])
        held = [b for b, x in r["blocks"].items() if not x["expected_ready"] and x["never_started"]]
        restarts = sum(x["restarts"] or 0 for x in r["blocks"].values() if x["expected_ready"])
        rows.append(
            f"| {r['test']} | {'PASS' if r['verdict'] else 'FAIL'} | {r['description']} | {ordered} | {r['converged_after_s']} | {restarts} | {held} | {r['stack_states']} |"
        )
    if not rows:
        return ""
    return (
        f"\n# Graph summary, Komodo {poc.VERSION}\n\n"
        "| test | verdict | construct | every block after its deps ready | all expected ready after s | restarts | blocked blocks never started | Stack states |\n"
        "|---|---|---|---|---|---|---|---|\n" + "\n".join(rows) + "\n"
    )
